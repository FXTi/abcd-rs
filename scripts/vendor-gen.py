def run_ruby_gen(
    gen_rb: pathlib.Path,
    data: pathlib.Path,
    requires: Sequence[pathlib.Path],
    template: pathlib.Path,
    output: pathlib.Path,
) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    req_arg = ",".join(str(r) for r in requires)
    cmd = [
        "ruby",
        "-rostruct",
        str(gen_rb),
        "-t",
        str(template),
        "-d",
        str(data),
        "-r",
        req_arg,
        "-o",
        str(output),
    ]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        fail(
            f"Ruby codegen failed for {template.name} (exit {res.returncode}):\n"
            f"{res.stderr}"
        )


def run_rustfmt(path: pathlib.Path) -> None:
    res = subprocess.run(
        ["rustfmt", "--edition", "2024", str(path)],
        capture_output=True,
        text=True,
    )
    if res.returncode != 0:
        fail(f"rustfmt failed on {path}:\n{res.stderr}")


