# Snapshot export & SHA-256 verification
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class SnapshotEntry:
    src: pathlib.Path
    rel: str


def enumerate_upstream_subset(src_root: pathlib.Path) -> List[SnapshotEntry]:
    entries: List[SnapshotEntry] = []
    lic = src_root / "LICENSE"
    if not lic.is_file():
        fail(f"missing LICENSE in upstream source root {src_root}")
    entries.append(SnapshotEntry(lic, "LICENSE"))

    for st in SUBTREES:
        base = src_root / st
        if not base.is_dir():
            fail(f"missing expected upstream subtree: {base}")
        for dirpath, dirnames, filenames in os.walk(base):
            # Prune test/hidden directories in-place so NTFS-hostile paths and
            # dead test fixtures never enter the snapshot.
            dirnames[:] = sorted(
                d
                for d in dirnames
                if d not in SKIP_DIR_NAMES and not d.startswith(".")
            )
            for fname in sorted(filenames):
                if fname.startswith("."):
                    continue
                full = pathlib.Path(dirpath) / fname
                if full.is_symlink() or not full.is_file():
                    continue
                rel = full.relative_to(src_root).as_posix()
                entries.append(SnapshotEntry(full, rel))

    entries.sort(key=lambda e: e.rel)
    return entries


def populate_snapshot(
    src_root: pathlib.Path,
    repo: str,
    tag: str,
    commit: str,
) -> None:
    entries = enumerate_upstream_subset(src_root)
    if SNAPSHOT_DIR.exists():
        shutil.rmtree(SNAPSHOT_DIR)
    SNAPSHOT_DIR.mkdir(parents=True, exist_ok=True)

    hashes: Dict[str, str] = {}
    for entry in entries:
        dst = SNAPSHOT_DIR / entry.rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(entry.src, dst)
        hashes[entry.rel] = sha256_file(dst)

    write_upstream_toml(UPSTREAM_TOML, repo, tag, commit, hashes)
    print(
        f"Exported {len(hashes)} files into {SNAPSHOT_DIR.relative_to(REPO_ROOT)} "
        f"(commit {commit[:12]}, tag {tag or '<none>'})"
    )


def verify_snapshot() -> None:
    meta, expected = parse_upstream_toml(UPSTREAM_TOML)
    if not SNAPSHOT_DIR.is_dir():
        fail(f"missing snapshot directory {SNAPSHOT_DIR}")

    actual: Dict[str, str] = {}
    for dirpath, dirnames, filenames in os.walk(SNAPSHOT_DIR):
        dirnames[:] = sorted(d for d in dirnames if d != ".DS_Store")
        for fname in sorted(filenames):
            if fname == ".DS_Store":
                continue
            full = pathlib.Path(dirpath) / fname
            rel = full.relative_to(SNAPSHOT_DIR).as_posix()
            actual[rel] = sha256_file(full)

    missing = sorted(set(expected) - set(actual))
    extra = sorted(set(actual) - set(expected))
    modified = sorted(
        k for k in (set(expected) & set(actual)) if expected[k] != actual[k]
    )

    if missing or extra or modified:
        details: List[str] = []
        if missing:
            details.append(f"  missing ({len(missing)}): {missing[:10]}")
        if extra:
            details.append(f"  unexpected ({len(extra)}): {extra[:10]}")
        if modified:
            details.append(f"  modified ({len(modified)}): {modified[:10]}")
        fail(
            "vendor snapshot drift detected against vendor/UPSTREAM.toml "
            f"(pinned {meta.get('commit', '?')}):\n" + "\n".join(details)
        )
    print(
        f"Snapshot verified: {len(actual)} files match vendor/UPSTREAM.toml "
        f"({meta.get('tag', '')} @ {meta.get('commit', '')[:12]})"
    )


