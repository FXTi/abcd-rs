@dataclass(frozen=True)
class CodegenTargets:
    vendor_gen: pathlib.Path
    isa_bridge_gen: pathlib.Path
    isa_src_gen: pathlib.Path
    file_src_gen: pathlib.Path


def default_targets() -> CodegenTargets:
    return CodegenTargets(
        vendor_gen=VENDOR_GEN_DIR,
        isa_bridge_gen=ISA_SYS_DIR / "bridge" / "generated",
        isa_src_gen=ISA_SYS_DIR / "src" / "generated",
        file_src_gen=FILE_SYS_DIR / "src" / "generated",
    )


def run_codegen_into(targets: CodegenTargets) -> None:
    if not SNAPSHOT_DIR.is_dir():
        fail(f"missing {SNAPSHOT_DIR} — run `sync` first")

    for d in (
        targets.vendor_gen,
        targets.isa_bridge_gen,
        targets.isa_src_gen,
        targets.file_src_gen,
    ):
        d.mkdir(parents=True, exist_ok=True)

    gen_rb = SNAPSHOT_DIR / "isa" / "gen.rb"
    isa_yaml = SNAPSHOT_DIR / "isa" / "isa.yaml"
    isapi = SNAPSHOT_DIR / "isa" / "isapi.rb"
    pf_dir = SNAPSHOT_DIR / "libpandafile"
    pf_isapi = pf_dir / "pandafile_isapi.rb"
    pf_tpl = pf_dir / "templates"
    isa_tpl = ISA_SYS_DIR / "templates"

    # 1. Shared vendor C++ headers (used by isa-sys and/or file-sys)
    run_ruby_gen(
        gen_rb,
        isa_yaml,
        [SNAPSHOT_DIR / "templates" / "plugin_options.rb"],
        pf_tpl / "source_lang_enum.h.erb",
        targets.vendor_gen / "source_lang_enum.h",
    )
    run_ruby_gen(
        gen_rb,
        pf_dir / "types.yaml",
        [pf_dir / "types.rb"],
        pf_tpl / "type.h.erb",
        targets.vendor_gen / "type.h",
    )
    for erb_name, out_name in [
        ("file_format_version.h.erb", "file_format_version.h"),
        ("bytecode_instruction_enum_gen.h.erb", "bytecode_instruction_enum_gen.h"),
        ("bytecode_instruction-inl_gen.h.erb", "bytecode_instruction-inl_gen.h"),
        ("bytecode_emitter_def_gen.h.erb", "bytecode_emitter_def_gen.h"),
        ("bytecode_emitter_gen.h.erb", "bytecode_emitter_gen.h"),
    ]:
        run_ruby_gen(
            gen_rb,
            isa_yaml,
            [isapi, pf_isapi],
            pf_tpl / erb_name,
            targets.vendor_gen / out_name,
        )

    # 2. abcd-isa-sys generated C++ & Rust
    for erb_name, out_name in [
        ("isa_bridge_emit_dispatch.h.erb", "isa_bridge_emit_dispatch.h"),
        ("isa_bridge_valid_opcode.h.erb", "isa_bridge_valid_opcode.h"),
    ]:
        run_ruby_gen(
            gen_rb,
            isa_yaml,
            [isapi, pf_isapi],
            isa_tpl / erb_name,
            targets.isa_bridge_gen / out_name,
        )

    bytecode_rs = targets.isa_src_gen / "bytecode.rs"
    run_ruby_gen(
        gen_rb,
        isa_yaml,
        [isapi, pf_isapi],
        isa_tpl / "bytecode.rs.erb",
        bytecode_rs,
    )
    run_rustfmt(bytecode_rs)

    isa_bindings_rs = targets.isa_src_gen / "bindings.rs"
    isa_bindings_rs.write_text(
        generate_c_bridge_bindings(
            ISA_SYS_DIR / "bridge" / "isa_bridge.h",
            ("isa_", "Isa", "ISA_"),
        ),
        encoding="utf-8",
    )
    run_rustfmt(isa_bindings_rs)

    # 3. abcd-file-sys generated Rust & C++ static_assert checks
    enum_rs_text, enum_cpp_checks = generate_vendor_enums(
        SNAPSHOT_DIR, targets.vendor_gen
    )
    bridge_enum_checks: List[str] = []
    file_bindings_rs = targets.file_src_gen / "bindings.rs"
    file_bindings_rs.write_text(
        generate_c_bridge_bindings(
            FILE_SYS_DIR / "bridge" / "file_bridge.h",
            ("abc_", "Abc", "ABC_"),
            extra_cpp_checks=bridge_enum_checks,
        ),
        encoding="utf-8",
    )
    run_rustfmt(file_bindings_rs)

    enum_bindings_rs = targets.file_src_gen / "enum_bindings.rs"
    enum_bindings_rs.write_text(enum_rs_text, encoding="utf-8")
    run_rustfmt(enum_bindings_rs)

    if bridge_enum_checks:
        enum_cpp_checks += "\n// Bridge C enum checks\n" + "\n".join(bridge_enum_checks) + "\n"
    (targets.vendor_gen / "file_bridge_enum_checks.h").write_text(
        enum_cpp_checks, encoding="utf-8"
    )


def compare_dirs(want_dir: pathlib.Path, got_dir: pathlib.Path, label: str) -> List[str]:
    errors: List[str] = []
    want_files = (
        {
            p.relative_to(want_dir).as_posix(): p
            for p in want_dir.rglob("*")
            if p.is_file() and p.name != ".DS_Store"
        }
        if want_dir.is_dir()
        else {}
    )
    got_files = (
        {
            p.relative_to(got_dir).as_posix(): p
            for p in got_dir.rglob("*")
            if p.is_file() and p.name != ".DS_Store"
        }
        if got_dir.is_dir()
        else {}
    )
    for m in sorted(set(want_files) - set(got_files)):
        errors.append(f"[{label}] missing committed generated file: {m}")
    for e in sorted(set(got_files) - set(want_files)):
        errors.append(f"[{label}] unexpected stale file in generated dir: {e}")
    for rel in sorted(set(want_files) & set(got_files)):
        wb = want_files[rel].read_bytes()
        gb = got_files[rel].read_bytes()
        if wb != gb:
            wlines = wb.decode("utf-8", errors="replace").splitlines(keepends=True)
            glines = gb.decode("utf-8", errors="replace").splitlines(keepends=True)
            diff = "".join(
                list(
                    difflib.unified_diff(
                        glines,
                        wlines,
                        fromfile=f"committed/{label}/{rel}",
                        tofile=f"fresh/{label}/{rel}",
                    )
                )[:60]
            )
            errors.append(f"[{label}] drift in {rel}:\n{diff}")
    return errors


