def strip_c_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


UNDERLYING_BITS: Dict[str, int] = {
    "uint8_t": 8,
    "uint16_t": 16,
    "uint32_t": 32,
    "uint64_t": 64,
}


def eval_int_expr(
    expr: str, env: Dict[str, int], context: str, width_bits: int = 32
) -> int:
    s = expr.strip()
    m_ctz = re.fullmatch(r"Ctz\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)", s)
    if m_ctz:
        target = m_ctz.group(1)
        if target not in env:
            fail(f"{context}: unknown Ctz argument {target!r}")
        val = env[target]
        if val == 0:
            fail(f"{context}: Ctz(0) is undefined")
        return (val & -val).bit_length() - 1

    # Iterative two-stack Shunting-Yard evaluator (zero recursion, zero Python eval,
    # exact C++ unsigned bitwise complement semantics masked to `width_bits`).
    mask = (1 << width_bits) - 1
    tokens = re.findall(
        r"0x[0-9a-fA-F]+[uUlL]*|\d+[uUlL]*|[A-Za-z_][A-Za-z0-9_]*|<<|>>|[|&^~()+-]",
        s,
    )
    if "".join(tokens) != re.sub(r"\s+", "", s):
        fail(f"{context}: unsupported constant expression {expr!r}")

    prec = {
        "u+": 7,
        "u-": 7,
        "u~": 7,
        "+": 5,
        "-": 5,
        "<<": 4,
        ">>": 4,
        "&": 3,
        "^": 2,
        "|": 1,
    }
    right_assoc = {"u+", "u-", "u~"}

    values: List[int] = []
    ops: List[str] = []

    def apply_top() -> None:
        if not ops:
            fail(f"{context}: malformed operator stack in {expr!r}")
        op = ops.pop()
        if op in right_assoc:
            if not values:
                fail(f"{context}: missing unary operand in {expr!r}")
            a = values.pop()
            if op == "u+":
                values.append(a & mask)
            elif op == "u-":
                values.append((-a) & mask)
            else:
                values.append((~a) & mask)
            return
        if len(values) < 2:
            fail(f"{context}: missing binary operand in {expr!r}")
        b = values.pop()
        a = values.pop()
        if op == "+":
            values.append((a + b) & mask)
        elif op == "-":
            values.append((a - b) & mask)
        elif op == "<<":
            values.append((a << b) & mask)
        elif op == ">>":
            values.append((a & mask) >> b)
        elif op == "&":
            values.append((a & b) & mask)
        elif op == "^":
            values.append((a ^ b) & mask)
        elif op == "|":
            values.append((a | b) & mask)
        else:
            fail(f"{context}: unknown operator {op!r}")

    expect_operand = True
    for tok in tokens:
        if tok == "(":
            ops.append("(")
            expect_operand = True
        elif tok == ")":
            while ops and ops[-1] != "(":
                apply_top()
            if not ops or ops[-1] != "(":
                fail(f"{context}: unbalanced parentheses in {expr!r}")
            ops.pop()
            expect_operand = False
        elif tok in ("+", "-", "~") and expect_operand:
            uop = f"u{tok}"
            while ops and ops[-1] != "(" and prec[ops[-1]] > prec[uop]:
                apply_top()
            ops.append(uop)
            expect_operand = True
        elif tok in prec:
            if expect_operand:
                fail(f"{context}: unexpected binary operator {tok!r} in {expr!r}")
            while ops and ops[-1] != "(" and prec[ops[-1]] >= prec[tok]:
                apply_top()
            ops.append(tok)
            expect_operand = True
        else:
            if not expect_operand:
                fail(f"{context}: missing operator before {tok!r} in {expr!r}")
            stripped = tok.rstrip("uUlL")
            if stripped.startswith(("0x", "0X")):
                values.append(int(stripped, 16) & mask)
            elif stripped.isdigit():
                values.append(int(stripped, 10) & mask)
            elif tok in env:
                values.append(env[tok] & mask)
            else:
                fail(f"{context}: unknown identifier {tok!r} in {expr!r}")
            expect_operand = False

    if expect_operand:
        fail(f"{context}: trailing operator in {expr!r}")
    while ops:
        if ops[-1] == "(":
            fail(f"{context}: unclosed parenthesis in {expr!r}")
        apply_top()
    if len(values) != 1:
        fail(f"{context}: expression {expr!r} did not reduce to a single value")
    return values[0]


def parse_cpp_enum_class(
    header_path: pathlib.Path,
    enum_name: str,
    expected_underlying: str,
) -> List[Tuple[str, int]]:
    clean = strip_c_comments(header_path.read_text(encoding="utf-8"))
    pattern = re.compile(
        rf"enum\s+class\s+{re.escape(enum_name)}\s*:\s*([A-Za-z0-9_]+)\s*\{{([^}}]*)\}}",
        re.S,
    )
    m = pattern.search(clean)
    if not m:
        fail(f"{header_path}: could not find `enum class {enum_name}`")
    underlying = m.group(1).strip()
    if underlying != expected_underlying:
        fail(
            f"{header_path}: expected `{enum_name} : {expected_underlying}`, "
            f"got `{underlying}`"
        )
    body = m.group(2)
    env: Dict[str, int] = {}
    items: List[Tuple[str, int]] = []
    next_val = 0
    for raw_entry in body.split(","):
        entry = raw_entry.strip()
        if not entry:
            continue
        if "=" in entry:
            name_part, expr_part = entry.split("=", 1)
            name = name_part.strip()
            val = eval_int_expr(expr_part, env, f"{header_path}:{enum_name}::{name}", UNDERLYING_BITS.get(underlying, 32))
        else:
            name = entry
            val = next_val
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            fail(f"{header_path}: invalid enumerator name {name!r} in {enum_name}")
        env[name] = val
        items.append((name, val))
        next_val = val + 1
    if not items:
        fail(f"{header_path}: `{enum_name}` has zero enumerators")
    return items


def parse_modifiers_acc(modifiers_h: pathlib.Path) -> List[Tuple[str, int]]:
    clean = strip_c_comments(modifiers_h.read_text(encoding="utf-8"))
    env: Dict[str, int] = {}
    items: List[Tuple[str, int]] = []
    stmt_re = re.compile(
        r"(?:static\s+)?constexpr\s+uint32_t\s+(ACC_[A-Za-z0-9_]+)\s*=\s*([^;]+);"
    )
    for m in stmt_re.finditer(clean):
        name, expr = m.group(1), m.group(2)
        val = eval_int_expr(expr, env, f"{modifiers_h}:{name}")
        if not (0 <= val <= 0xFFFF_FFFF):
            fail(f"{modifiers_h}:{name} out of u32 range: {val}")
        env[name] = val
        items.append((name, val))
    if not items:
        fail(f"{modifiers_h}: no ACC_* constexpr definitions found")
    return items


def generate_vendor_enums(
    snapshot_dir: pathlib.Path,
    vendor_gen_dir: pathlib.Path,
) -> Tuple[str, str]:
    pf = snapshot_dir / "libpandafile"
    enum_specs = [
        (
            vendor_gen_dir / "type.h",
            "TypeId",
            "uint8_t",
            "Type_TypeId",
            "u8",
            "panda::panda_file::Type::TypeId",
        ),
        (
            vendor_gen_dir / "source_lang_enum.h",
            "SourceLang",
            "uint8_t",
            "SourceLang",
            "u8",
            "panda::panda_file::SourceLang",
        ),
        (
            pf / "file_items.h",
            "FunctionKind",
            "uint8_t",
            "FunctionKind",
            "u8",
            "panda::panda_file::FunctionKind",
        ),
        (
            pf / "file_items.h",
            "MethodHandleType",
            "uint8_t",
            "MethodHandleType",
            "u8",
            "panda::panda_file::MethodHandleType",
        ),
        (
            pf / "literal_data_accessor.h",
            "LiteralTag",
            "uint8_t",
            "LiteralTag",
            "u8",
            "panda::panda_file::LiteralTag",
        ),
        (
            pf / "module_data_accessor.h",
            "ModuleTag",
            "uint8_t",
            "ModuleTag",
            "u8",
            "panda::panda_file::ModuleTag",
        ),
    ]

    rs_lines = [
        "// Auto-generated by scripts/vendor-gen.py from vendor headers — do not edit.",
        "",
    ]
    cpp_lines = [
        "// Auto-generated by scripts/vendor-gen.py — do not edit.",
        "// Included by file_bridge.cpp to pin every Rust constant against vendor C++.",
        "#pragma once",
        "",
    ]

    for hdr, cpp_enum, cpp_ty, rs_ty_name, rs_ty, cpp_qual in enum_specs:
        variants = parse_cpp_enum_class(hdr, cpp_enum, cpp_ty)
        rs_lines.append(f"pub type {rs_ty_name} = {rs_ty};")
        for vname, val in variants:
            rs_lines.append(
                f"pub const {rs_ty_name}_{vname}: {rs_ty_name} = {val};"
            )
            cpp_lines.append(
                f"static_assert(static_cast<{cpp_ty}>({cpp_qual}::{vname}) == {val}u);"
            )
        rs_lines.append("")
        cpp_lines.append("")

    acc_items = parse_modifiers_acc(pf / "modifiers.h")
    rs_lines.append("pub type AbcAccessFlags = u32;")
    for name, val in acc_items:
        rs_lines.append(f"pub const AbcAccessFlags_ABC_{name}: AbcAccessFlags = {val};")
        cpp_lines.append(f"static_assert(panda::{name} == {val}u);")
    rs_lines.append("")

    return "\n".join(rs_lines), "\n".join(cpp_lines) + "\n"


