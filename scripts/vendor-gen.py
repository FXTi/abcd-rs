import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence, Tuple

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
VENDOR_DIR = REPO_ROOT / "vendor"
SNAPSHOT_DIR = VENDOR_DIR / "arkcompiler_runtime_core"
UPSTREAM_TOML = VENDOR_DIR / "UPSTREAM.toml"
VENDOR_GEN_DIR = VENDOR_DIR / "generated"

ISA_SYS_DIR = REPO_ROOT / "abcd-isa-sys"
FILE_SYS_DIR = REPO_ROOT / "abcd-file-sys"

DEFAULT_REPO = "https://github.com/openharmony/arkcompiler_runtime_core.git"
SUBTREES: Tuple[str, ...] = (
    "isa",
    "libpandafile",
    "libpandabase",
    "assembler",
    "templates",
    "platforms",
)
SKIP_DIR_NAMES = {"test", "tests", "unittest", "benchmarks"}


def fail(msg: str) -> "NoReturn":  # type: ignore[name-defined]
    print(f"vendor-gen error: {msg}", file=sys.stderr)
    raise SystemExit(1)


def sha256_file(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


# ---------------------------------------------------------------------------
# UPSTREAM.toml read / write
# ---------------------------------------------------------------------------


def write_upstream_toml(
    dest: pathlib.Path,
    repo: str,
    tag: str,
    commit: str,
    files: Dict[str, str],
) -> None:
    lines = [
        "# Auto-generated by scripts/vendor-gen.py — do not edit manually.",
        f'repository = "{repo}"',
        f'tag = "{tag}"',
        f'commit = "{commit}"',
        "subtrees = [" + ", ".join(f'"{s}"' for s in SUBTREES) + "]",
        "",
        "[files]",
    ]
    for rel in sorted(files):
        lines.append(f'"{rel}" = "{files[rel]}"')
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_upstream_toml(path: pathlib.Path) -> Tuple[Dict[str, str], Dict[str, str]]:
    if not path.is_file():
        fail(f"missing {path}")
    meta: Dict[str, str] = {}
    files: Dict[str, str] = {}
    in_files = False
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line == "[files]":
            in_files = True
            continue
        if not in_files:
            m = re.match(r'^([a-z_]+)\s*=\s*"([^"]*)"$', line)
            if m:
                meta[m.group(1)] = m.group(2)
            elif line.startswith("subtrees ="):
                continue
            else:
                fail(f"{path}:{lineno}: unexpected header line: {raw}")
        else:
            m = re.match(r'^"([^"]+)"\s*=\s*"([0-9a-f]{64})"$', line)
            if not m:
                fail(f"{path}:{lineno}: malformed file hash entry: {raw}")
            files[m.group(1)] = m.group(2)
    return meta, files


