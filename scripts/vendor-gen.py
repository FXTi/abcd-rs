#!/usr/bin/env python3
"""Offline upstream vendor snapshot & FFI/ISA code generator for abcd-rs.

Subcommands:
  sync     Populate `vendor/arkcompiler_runtime_core/` from an upstream git
           commit (or `--from-local` checkout), write `vendor/UPSTREAM.toml`
           with a full per-file SHA-256 manifest, and run `codegen`.
  codegen  Regenerate all pre-generated C++ headers and Rust FFI/ISA bindings
           under `vendor/generated/`, `abcd-isa-sys/`, and `abcd-file-sys/`.
  verify   Verify in CI that (1) every file in `vendor/arkcompiler_runtime_core/`
           matches `vendor/UPSTREAM.toml` with zero local edits or stray files,
           and (2) every committed generated file is byte-identical to a fresh
           `codegen` run.

Ordinary `cargo build` / `cargo test` runs NEVER invoke this script, Ruby, or
bindgen — they compile pure C++ + Rust directly from the committed snapshot and
generated sources.
"""

from __future__ import annotations

