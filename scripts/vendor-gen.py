def cmd_sync(args: argparse.Namespace) -> None:
    if args.from_local:
        local_root = pathlib.Path(args.from_local).resolve()
        commit = args.commit
        if not commit:
            res = subprocess.run(
                ["git", "-C", str(local_root), "rev-parse", "HEAD"],
                capture_output=True,
                text=True,
                check=True,
            )
            commit = res.stdout.strip()
        populate_snapshot(local_root, args.repo, args.tag or "", commit)
    else:
        if not args.commit:
            fail("`sync` requires `--commit <sha>` (or `--from-local <dir>`)")
        with tempfile.TemporaryDirectory(prefix="abcd-vendor-sync-") as tmp:
            clone_dir = pathlib.Path(tmp) / "upstream"
            subprocess.run(
                [
                    "git",
                    "-c",
                    "core.protectNTFS=false",
                    "-c",
                    "core.longpaths=true",
                    "clone",
                    "--quiet",
                    "--depth",
                    "1",
                    "--filter=blob:none",
                    "--sparse",
                    args.repo,
                    str(clone_dir),
                ],
                check=True,
            )
            subprocess.run(
                [
                    "git",
                    "-C",
                    str(clone_dir),
                    "sparse-checkout",
                    "set",
                    "--cone",
                    *SUBTREES,
                ],
                check=True,
            )
            subprocess.run(
                [
                    "git",
                    "-C",
                    str(clone_dir),
                    "fetch",
                    "--quiet",
                    "--depth",
                    "1",
                    "origin",
                    args.commit,
                ],
                check=True,
            )
            subprocess.run(
                [
                    "git",
                    "-C",
                    str(clone_dir),
                    "checkout",
                    "--quiet",
                    "-f",
                    args.commit,
                ],
                check=True,
            )
            resolved = subprocess.run(
                ["git", "-C", str(clone_dir), "rev-parse", "HEAD"],
                capture_output=True,
                text=True,
                check=True,
            ).stdout.strip()
            populate_snapshot(clone_dir, args.repo, args.tag or "", resolved)

    run_codegen_into(default_targets())
    print("Codegen complete.")


def cmd_codegen(_args: argparse.Namespace) -> None:
    run_codegen_into(default_targets())
    print("Codegen complete.")


def cmd_verify(_args: argparse.Namespace) -> None:
    verify_snapshot()
    committed = default_targets()
    with tempfile.TemporaryDirectory(prefix="abcd-vendor-verify-") as tmp:
        root = pathlib.Path(tmp)
        fresh = CodegenTargets(
            vendor_gen=root / "vendor_gen",
            isa_bridge_gen=root / "isa_bridge_gen",
            isa_sys_src_gen=root / "isa_sys_src_gen",
            isa_src_gen=root / "isa_src_gen",
            isa_test_gen=root / "isa_test_gen",
            file_sys_src_gen=root / "file_sys_src_gen",
            file_pandasm_gen=root / "file_pandasm_gen",
        )
        run_codegen_into(fresh)
        errs: List[str] = []
        for want_d, got_d, lbl in [
            (fresh.vendor_gen, committed.vendor_gen, "vendor/generated"),
            (fresh.isa_bridge_gen, committed.isa_bridge_gen, "abcd-isa-sys/bridge/generated"),
            (fresh.isa_sys_src_gen, committed.isa_sys_src_gen, "abcd-isa-sys/src/generated"),
            (fresh.isa_src_gen, committed.isa_src_gen, "abcd-isa/src/generated"),
            (fresh.isa_test_gen, committed.isa_test_gen, "abcd-isa/tests/integration/generated"),
            (fresh.file_sys_src_gen, committed.file_sys_src_gen, "abcd-file-sys/src/generated"),
            (fresh.file_pandasm_gen, committed.file_pandasm_gen, "abcd-file/src/pandasm/generated"),
        ]:
            errs.extend(compare_dirs(want_d, got_d, lbl))
        if errs:
            fail(
                "pre-generated files are out of sync (run `python3 scripts/vendor-gen.py codegen`):\n"
                + "\n".join(errs)
            )
    print("Generated files verified: 100% byte-identical to fresh codegen.")


def handle_cli() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_sync = sub.add_parser("sync", help="Export upstream snapshot and run codegen")
    p_sync.add_argument("--repo", default=DEFAULT_REPO, help="Upstream git URL")
    p_sync.add_argument("--tag", default="", help="Upstream release tag name")
    p_sync.add_argument("--commit", default="", help="Upstream commit SHA")
    p_sync.add_argument(
        "--from-local",
        default="",
        help="Populate snapshot from an existing local upstream checkout",
    )
    p_sync.set_defaults(func=cmd_sync)

    p_cg = sub.add_parser("codegen", help="Regenerate C++ and Rust bindings from vendor/")
    p_cg.set_defaults(func=cmd_codegen)

    p_vf = sub.add_parser("verify", help="Verify vendor snapshot and generated bindings")
    p_vf.set_defaults(func=cmd_verify)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    handle_cli()
