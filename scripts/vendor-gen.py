RUST_PRIMITIVES: Dict[str, str] = {
    "void": "()",
    "uint8_t": "u8",
    "int8_t": "i8",
    "uint16_t": "u16",
    "int16_t": "i16",
    "uint32_t": "u32",
    "int32_t": "i32",
    "uint64_t": "u64",
    "int64_t": "i64",
    "size_t": "usize",
    "float": "f32",
    "double": "f64",
    "int": "::std::os::raw::c_int",
    "unsigned int": "::std::os::raw::c_uint",
    "char": "::std::os::raw::c_char",
}

RUST_KEYWORDS = {
    "as", "async", "await", "box", "break", "const", "continue", "crate", "dyn",
    "else", "enum", "extern", "false", "fn", "for", "gen", "if", "impl", "in",
    "let", "loop", "macro", "match", "mod", "move", "mut", "priv", "pub", "ref",
    "return", "self", "Self", "static", "struct", "super", "trait", "true",
    "try", "type", "typeof", "unsafe", "unsized", "use", "virtual", "where",
    "while", "yield",
}


def sanitize_rust_ident(name: str) -> str:
    return f"{name}_" if name in RUST_KEYWORDS else name


def split_top_level_Comma(param_str: str) -> List[str]:
    parts: List[str] = []
    depth = 0
    start = 0
    for i, ch in enumerate(param_str):
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == "," and depth == 0:
            parts.append(param_str[start:i].strip())
            start = i + 1
    tail = param_str[start:].strip()
    if tail:
        parts.append(tail)
    return parts


def map_c_base_type(base: str, context: str) -> str:
    b = re.sub(r"\s+", " ", base.strip())
    for prefix in ("struct ", "union ", "enum "):
        if b.startswith(prefix):
            b = b[len(prefix) :].strip()
    if b in RUST_PRIMITIVES:
        return RUST_PRIMITIVES[b]
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", b):
        return b
    fail(f"{context}: unsupported C base type {base!r}")


def map_c_type(c_type: str, context: str, is_param: bool = False) -> str:
    s = re.sub(r"\s+", " ", c_type.strip())
    # Pointer layers: handle `const T *`, `T *`, `uint8_t **`, etc.
    # Tokenize into base tokens and pointer stars.
    if "*" not in s:
        if s.startswith("const "):
            s = s[len("const ") :].strip()
        return map_c_base_type(s, context)

    # Split at the first `*`
    first_star = s.index("*")
    left = s[:first_star].strip()
    stars_part = s[first_star:].strip()

    is_base_const = False
    if left.startswith("const "):
        is_base_const = True
        left = left[len("const ") :].strip()
    elif left.endswith(" const"):
        is_base_const = True
        left = left[: -len(" const")].strip()

    if left == "void":
        inner = "::std::os::raw::c_void"
    else:
        inner = map_c_base_type(left, context)

    star_tokens = [t.strip() for t in stars_part.split("*")[1:]]
    # First pointer applies `is_base_const`
    cur = f"*{'const' if is_base_const else 'mut'} {inner}"
    for qual in star_tokens[1:]:
        if qual == "const":
            cur = f"*const {cur}"
        elif qual == "":
            cur = f"*mut {cur}"
        else:
            fail(f"{context}: unsupported pointer qualifier {qual!r} in {c_type!r}")
    return cur


def parse_c_param(raw_param: str, idx: int, context: str) -> Tuple[str, str]:
    p = re.sub(r"\s+", " ", raw_param.strip())
    # Inline function pointer parameter, e.g.: `void (*cb)(uint8_t flag, void *ctx)`
    m_fp = re.fullmatch(r"(.+?)\(\*\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)\((.*)\)", p)
    if m_fp:
        ret_c, name, inner_params = m_fp.group(1).strip(), m_fp.group(2), m_fp.group(3)
        fn_ty = format_fn_ptr_option(ret_c, inner_params, f"{context}:{name}")
        return sanitize_rust_ident(name), fn_ty

    # Fixed-size array parameter decay, e.g. `const uint8_t ver[4]` or `uint8_t out[4]`
    m_arr = re.fullmatch(r"(.+?)\b([A-Za-z_][A-Za-z0-9_]*)\s*\[\d*\]", p)
    if m_arr:
        elem_c, name = m_arr.group(1).strip(), m_arr.group(2)
        is_const = False
        if elem_c.startswith("const "):
            is_const = True
            elem_c = elem_c[len("const ") :].strip()
        elem_rs = map_c_base_type(elem_c, f"{context}:{name}")
        return sanitize_rust_ident(name), f"*{'const' if is_const else 'mut'} {elem_rs}"

    m = re.fullmatch(r"(.+?[\s\*])([A-Za-z_][A-Za-z0-9_]*)", p)
    if not m:
        fail(f"{context}: cannot parse parameter #{idx}: {raw_param!r}")
    ty_c, name = m.group(1).strip(), m.group(2)
    return sanitize_rust_ident(name), map_c_type(ty_c, f"{context}:{name}", is_param=True)


def format_fn_ptr_option(ret_c: str, params_c: str, context: str) -> str:
    params_clean = params_c.strip()
    rendered_params: List[str] = []
    if params_clean and params_clean != "void":
        for i, rp in enumerate(split_top_level_Comma(params_clean)):
            pname, pty = parse_c_param(rp, i, context)
            rendered_params.append(f"{pname}: {pty}")
    ret_rs = map_c_type(ret_c, f"{context}:ret")
    ret_part = "" if ret_rs == "()" else f" -> {ret_rs}"
    return (
        f"::std::option::Option<unsafe extern \"C\" fn({', '.join(rendered_params)}){ret_part}>"
    )


def generate_c_bridge_bindings(
    header_path: pathlib.Path,
    allow_prefix: Tuple[str, str, str],
    extra_cpp_checks: Optional[List[str]] = None,
) -> str:
    fn_pref, ty_pref, var_pref = allow_prefix
    raw_text = header_path.read_text(encoding="utf-8")
    no_comments = strip_c_comments(raw_text)

    out_lines: List[str] = [
        f"// Auto-generated by scripts/vendor-gen.py from {header_path.name} — do not edit.",
        "",
    ]

    # 1. Extract `#define` integer constants matching `var_pref`
    clean_lines: List[str] = []
    for line in no_comments.splitlines():
        s = line.strip()
        if not s:
            continue
        if s.startswith("#"):
            m_def = re.fullmatch(r"#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(-?\d+)", s)
            if m_def:
                cname, cval_s = m_def.group(1), m_def.group(2)
                if cname.startswith(var_pref):
                    cval = int(cval_s)
                    rty = "i32" if cval < 0 else "u32"
                    out_lines.append(f"pub const {cname}: {rty} = {cval};")
            continue
        clean_lines.append(line)

    body = "\n".join(clean_lines)
    # Strip `extern "C" {` and matching closing `}`
    body = re.sub(r'extern\s+"C"\s*\{', "", body)
    # Remove standalone closing brace from extern "C" if unbalanced
    if body.count("{") < body.count("}"):
        last_brace = body.rfind("}")
        if last_brace != -1:
            body = body[:last_brace] + body[last_brace + 1 :]

    # Split top-level C declarations on `;` outside `{...}`
    stmts: List[str] = []
    depth = 0
    start = 0
    for i, ch in enumerate(body):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        elif ch == ";" and depth == 0:
            stmt = body[start:i].strip()
            if stmt:
                stmts.append(stmt)
            start = i + 1

    trailing = body[start:].strip()
    if trailing:
        fail(f"{header_path}: unparsed trailing text: {trailing!r}")

    union_types: set[str] = set()

    for stmt in stmts:
        norm = re.sub(r"\s+", " ", stmt).strip()

        # Case 1: Opaque struct `typedef struct Foo Foo`
        m = re.fullmatch(
            r"typedef struct ([A-Za-z_][A-Za-z0-9_]*) ([A-Za-z_][A-Za-z0-9_]*)", norm
        )
        if m:
            tag_name, alias_name = m.group(1), m.group(2)
            if tag_name != alias_name:
                fail(f"{header_path}: mismatched opaque typedef {norm!r}")
            if alias_name.startswith(ty_pref):
                out_lines.extend(
                    [
                        "#[repr(C)]",
                        "#[derive(Debug, Copy, Clone)]",
                        f"pub struct {alias_name} {{",
                        "    _unused: [u8; 0],",
                        "}",
                    ]
                )
            continue

        # Case 2: `typedef struct Name { ... } Name` or `(struct|union) Name { ... }`
        m_td_struct = re.fullmatch(
            r"typedef (struct|union) ([A-Za-z_][A-Za-z0-9_]*)\s*\{(.*)\}\s*([A-Za-z_][A-Za-z0-9_]*)",
            norm,
        )
        m_struct = re.fullmatch(
            r"(struct|union) ([A-Za-z_][A-Za-z0-9_]*)\s*\{(.*)\}",
            norm,
        )
        if m_td_struct or m_struct:
            if m_td_struct:
                kind, sname, fbody, alias = (
                    m_td_struct.group(1),
                    m_td_struct.group(2),
                    m_td_struct.group(3),
                    m_td_struct.group(4),
                )
                if sname != alias:
                    fail(f"{header_path}: mismatched struct typedef {norm!r}")
            else:
                assert m_struct is not None
                kind, sname, fbody = (
                    m_struct.group(1),
                    m_struct.group(2),
                    m_struct.group(3),
                )
            if not sname.startswith(ty_pref):
                continue
            if kind == "union":
                union_types.add(sname)
            fields_rs: List[str] = []
            has_union_field = False
            for raw_f in fbody.split(";"):
                rf = raw_f.strip()
                if not rf:
                    continue
                fname, fty = parse_c_param(rf, 0, f"{header_path}:{sname}")
                if fty in union_types:
                    has_union_field = True
                fields_rs.append(f"    pub {fname}: {fty},")
            derives = (
                "#[derive(Copy, Clone)]"
                if (kind == "union" or has_union_field)
                else "#[derive(Debug, Copy, Clone)]"
            )
            out_lines.append("#[repr(C)]")
            out_lines.append(derives)
            out_lines.append(f"pub {kind} {sname} {{")
            out_lines.extend(fields_rs)
            out_lines.append("}")
            continue

        # Case 3: `enum Name { A, B, ... }`
        m_enum = re.fullmatch(r"enum ([A-Za-z_][A-Za-z0-9_]*)\s*\{(.*)\}", norm)
        if m_enum:
            ename, ebody = m_enum.group(1), m_enum.group(2)
            if not ename.startswith(ty_pref):
                continue
            val = 0
            for raw_v in ebody.split(","):
                v = raw_v.strip()
                if not v:
                    continue
                if "=" in v:
                    fail(f"{header_path}: explicit value in C enum {ename} unsupported")
                out_lines.append(f"pub const {ename}_{v}: {ename} = {val};")
                if extra_cpp_checks is not None:
                    extra_cpp_checks.append(
                        f"static_assert(static_cast<unsigned int>({v}) == {val}u);"
                    )
                val += 1
            out_lines.append(f"pub type {ename} = ::std::os::raw::c_uint;")
            continue

        # Case 4: Callback typedef `typedef ret (*Name)(params)`
        m_cb = re.fullmatch(
            r"typedef\s+(.+?)\(\*\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)\((.*)\)", norm
        )
        if m_cb:
            ret_c, cb_name, params_c = (
                m_cb.group(1).strip(),
                m_cb.group(2),
                m_cb.group(3),
            )
            if cb_name.startswith(ty_pref):
                fn_opt = format_fn_ptr_option(ret_c, params_c, f"{header_path}:{cb_name}")
                out_lines.append(f"pub type {cb_name} = {fn_opt};")
            continue

        # Case 5: Function prototype `ret func_name(params)`
        m_fn = re.fullmatch(r"(.+?[\s\*])([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)", norm)
        if m_fn:
            ret_c, fname, params_c = (
                m_fn.group(1).strip(),
                m_fn.group(2),
                m_fn.group(3).strip(),
            )
            if not fname.startswith(fn_pref):
                continue
            params_rs: List[str] = []
            if params_c and params_c != "void":
                for idx, rp in enumerate(split_top_level_Comma(params_c)):
                    pname, pty = parse_c_param(rp, idx, f"{header_path}:{fname}")
                    params_rs.append(f"{pname}: {pty}")
            ret_rs = map_c_type(ret_c, f"{header_path}:{fname}:ret")
            ret_part = "" if ret_rs == "()" else f" -> {ret_rs}"
            out_lines.append('unsafe extern "C" {')
            out_lines.append(
                f"    pub fn {fname}({', '.join(params_rs)}){ret_part};"
            )
            out_lines.append("}")
            continue

        fail(f"{header_path}: unrecognized C declaration: {norm!r}")

    out_lines.append("")
    return "\n".join(out_lines)


