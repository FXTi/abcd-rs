#!/usr/bin/env python3
"""Generate abcd-isa/src/legacy_table.rs — the legacy (file format 0.0.0.2)
opcode translation table.

Inputs (regenerate from upstream history; see design doc in the emitted
file's header comment):

  1. OLD table: the OpenHarmony 3.1-era ISA, generated from
     arkcompiler_runtime_core@OpenHarmony-v3.1-Release isa/isa.yaml combined
     (isa/combine.rb) with the last pre-2022-08-18-refactoring ecma_isa.yaml
     (arkcompiler_js_runtime commit cb7bc0f08, 2023-02-14), dumped via the
     upstream isa/gen.rb + isa/isapi.rb with a `sig|prefix|idx|fmt|size|ops`
     ERB template. Byte-level verified: this exact table decodes all 105,995
     instructions of the 11 wild 0.0.0.2 packages with zero unknown bytes.
  2. VARIANTS: the generated bytecode.rs of abcd-isa-sys (build artifact),
     used to validate variant names and field types.

Usage:
  gen_legacy_table.py OLD_TABLE VARIANTS_RS OUTPUT_RS

The mapping itself is the curated MAPPING dict below: legacy opcode ->
modern Bytecode variant + operand token list. Operand tokens:
  "0"          synthesized Imm(0) — modern IC-slot immediate the legacy
               format does not carry
  "v0".."v3"   legacy register operand i -> Reg
  "imm"        legacy immediate -> Imm (sign-extended when the legacy
               operand type is signed)
  "id"         legacy id operand -> EntityId (raw value; for strings a
               32-bit file offset, for methods a 16-bit index)
  "jmp"        legacy jump immediate -> Label(0), raw offset returned for
               the caller's jump-resolution pass
"""

