#
# key: (prefix, sub_opcode) with prefix 0x00 = legacy core (unprefixed),
#      0xff = legacy ecma prefix.
# value: (modern Bytecode variant, [operand tokens])
#
# Coverage notes:
#  - Every legacy opcode observed in the 11 wild 0.0.0.2 packages is mapped.
#  - Legacy Java-era core opcodes (movi/ldarr/call.virt/...) and ecma
#    opcodes with no modern counterpart (debugger, expdyn, iternext,
#    copymodule, newobjspreaddyn, ldfunction, newlexenvwithnamedyn) are
#    intentionally unmapped: they decode to InvalidOpcode, same as before.
#  - definefuncdyn / definencfuncdyn / definegeneratorfunc / defineasyncfunc /
#    defineasyncgeneratorfunc all map to modern `Definefunc`: the
#    2022-08-18 ISA refactoring merged them, moving the distinction into the
#    method header's function-kind field (which abcd-file decodes
#    separately). The legacy trailing lexenv register operand has no modern
#    counterpart (modern definefunc reads the frame env) and is dropped.
# ---------------------------------------------------------------------------

