def parse_table(path):
    prefixes = {}
    insns = []
    for line in open(path):
        line = line.rstrip("\n")
        if line.startswith("PREFIX|"):
            _, name, idx = line.split("|")
            prefixes[name] = int(idx)
        elif line.startswith("INSN|"):
            _, sig, prefix, idx, fmt, size, ops, acc, props = line.split("|")
            operands = []
            if ops:
                for o in ops.split(","):
                    name, srcdst, typ, width, offset = o.split(":")
                    operands.append(dict(name=name, type=typ,
                                         width=int(width), offset=int(offset)))
            insns.append(dict(sig=sig, prefix=None if prefix == "-" else prefix,
                              idx=int(idx), fmt=fmt, size=int(size),
                              operands=operands))
    return prefixes, insns


def parse_variants(path):
    """Parse `VariantName(Field, ...)` lines from generated bytecode.rs."""
    variants = {}
    enum_re = re.compile(r"^    ([A-Z][A-Za-z0-9]*)(\(([^)]*)\))?,\s*$")
    in_enum = False
    for line in open(path):
        if line.startswith("pub enum Bytecode"):
            in_enum = True
            continue
        if in_enum:
            if line.startswith("}"):
                break
            m = enum_re.match(line.rstrip("\n"))
            if m:
                fields = m.group(3).split(", ") if m.group(3) else []
                variants[m.group(1)] = fields
    return variants


def gen_extractor(op, signed):
    """Rust expression reading legacy operand `op` from `b` (insn start)."""
    off, width = op["offset"], op["width"]
    byte = off // 8
    if width == 4:
        return f"(b[{byte}] >> 4) & 0xf" if off % 8 else f"b[{byte}] & 0xf"
    if width == 8:
        return f"b[{byte}]"
    if width == 16:
        return f"u16::from_le_bytes([b[{byte}], b[{byte + 1}]])"
    if width == 32:
        return (f"u32::from_le_bytes([b[{byte}], b[{byte + 1}], "
                f"b[{byte + 2}], b[{byte + 3}]])")
    if width == 64:
        return (f"u64::from_le_bytes([b[{byte}], b[{byte + 1}], b[{byte + 2}], "
                f"b[{byte + 3}], b[{byte + 4}], b[{byte + 5}], b[{byte + 6}], "
                f"b[{byte + 7}]])")
    raise ValueError(f"unsupported width {width}")


def main():
    old_path, variants_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    old_prefixes, old = parse_table(old_path)
    variants = parse_variants(variants_path)
    assert old_prefixes.get("ecma") == 0xFF, "ecma prefix must be 0xff"

    old_by_key = {}
    for i in old:
        if i["prefix"] is None:
            old_by_key[(0x00, i["idx"])] = i
        elif i["prefix"] == "ecma":
            old_by_key[(0xFF, i["idx"])] = i
        # legacy f32/cast/unsigned/bit prefixes (Java-era): never mapped

    lines = []
    emit = lines.append
    emit("// @generated by abcd-isa/tools/gen_legacy_table.py — do not edit.")
    emit("//")
    emit("// Legacy (file format 0.0.0.2, OpenHarmony 3.0/3.1-era) opcode")
    emit("// translation table. Maps legacy opcodes onto modern `Bytecode` IR")
    emit("// variants. See the generator for provenance and the curated mapping.")
    emit("")
    emit("use abcd_isa_sys::{Bytecode, EntityId, Imm, Label, Reg};")
    emit("")
    emit("/// One legacy opcode table entry.")
    emit("#[derive(Clone, Copy)]")
    emit("pub(crate) struct LegacyInsn {")
    emit("    /// Total instruction size in bytes (legacy encoding).")
    emit("    pub size: u8,")
    emit("    /// Build the modern-IR instruction from the raw bytes starting at")
    emit("    /// the instruction. Returns the instruction plus the raw jump")
    emit("    /// offset for jump instructions (resolved by the caller).")
    emit("    pub make: fn(&[u8]) -> (Bytecode, Option<i64>),")
    emit("}")
    emit("")

    errors = []
    for key in sorted(MAPPING):
        pbyte, sub = key
        old_insn = old_by_key.get(key)
        if old_insn is None:
            errors.append(f"{key}: not in legacy table")
            continue
        variant, tokens = MAPPING[key]
        fields = variants.get(variant)
        if fields is None:
            errors.append(f"{key}: variant {variant} not in generated Bytecode")
            continue
        if len(fields) != len(tokens):
            errors.append(f"{key}: {variant} takes {len(fields)} operands, "
                          f"{len(tokens)} tokens")
            continue

        old_ops = old_insn["operands"]
        old_vs = [o for o in old_ops if o["name"] == "v"]
        old_imms = [o for o in old_ops if o["name"] == "imm"]
        old_ids = [o for o in old_ops if o["name"].endswith("id")]
        imm_i = 0
        args = []
        jump = None
        consumed = 0
        for field, tok in zip(fields, tokens):
            if tok == "0":
                assert field == "Imm", f"{key}: synth imm into {field}"
                args.append("Imm(0)")
            elif tok.startswith("v"):
                op = old_vs[int(tok[1:])]
                assert field == "Reg", f"{key}: {variant} field {field} != Reg"
                args.append(f"Reg({gen_extractor(op, False)} as u16)")
                consumed += 1
            elif tok == "imm":
                op = old_imms[imm_i]
                assert field == "Imm", f"{key}: {variant} field {field} != Imm"
                signed = op["type"].startswith("i") or op["type"].startswith("f")
                ex = gen_extractor(op, signed)
                if op["width"] == 64:
                    args.append(f"Imm({ex} as i64)")  # f64 bits
                elif signed:
                    args.append(f"Imm(({ex}) as i{op['width']} as i64)")
                else:
                    args.append(f"Imm(({ex}) as i64)")
                imm_i += 1
                consumed += 1
            elif tok == "id":
                op = old_ids[0]
                old_ids.pop(0)
                assert field == "EntityId", f"{key}: {variant} field {field}"
                args.append(f"EntityId(({gen_extractor(op, False)}) as u32)")
                consumed += 1
            elif tok == "jmp":
                op = next(o for o in old_ops if o["name"] == "imm")
                assert field == "Label"
                args.append("Label(0)")
                ex = gen_extractor(op, True)
                jump = f"Some(({ex}) as i{op['width']} as i64)"
                consumed += 1
            else:
                raise ValueError(f"unknown token {tok}")
        # every legacy operand must be consumed exactly once (except the
        # documented define*/definemethod lexenv-register drop)
        if consumed != len(old_ops) and variant not in ("Definefunc", "Definemethod"):
            errors.append(f"{key}: consumed {consumed} of {len(old_ops)} "
                          f"legacy operands")
            continue

        fname = f"mk_{'core' if pbyte == 0 else 'ecma'}_{sub:02x}"
        sig = old_insn["sig"]
        ctor = f"Bytecode::{variant}({', '.join(args)})" if args else f"Bytecode::{variant}"
        reads_bytes = any(t != "0" for t in tokens)
        param = "b: &[u8]" if reads_bytes else "_b: &[u8]"
        emit(f"/// legacy `{sig}` [{old_insn['fmt']}] -> `{variant}`")
        emit(f"fn {fname}({param}) -> (Bytecode, Option<i64>) {{")
        emit(f"    ({ctor}, {jump if jump else 'None'})")
        emit("}")
        emit("")

    if errors:
        for e in errors:
            print("ERROR:", e, file=sys.stderr)
        sys.exit(1)

    for pbyte, name in ((0x00, "LEGACY_CORE"), (0xFF, "LEGACY_ECMA")):
        emit(f"/// Legacy {'core (unprefixed)' if pbyte == 0 else '0xff-prefixed ecma'} opcode table.")
        emit(f"pub(crate) static {name}: [Option<LegacyInsn>; 256] = {{")
        emit("    let mut t = [None; 256];")
        for (p, sub), (variant, _tokens) in sorted(MAPPING.items()):
            if p != pbyte:
                continue
            old_insn = old_by_key[(p, sub)]
            emit(f"    t[0x{sub:02x}] = Some(LegacyInsn {{ size: "
                 f"{old_insn['size']}, make: mk_{'core' if p == 0 else 'ecma'}_{sub:02x} }});")
        emit("    t")
        emit("};")
        emit("")

    with open(out_path, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out_path}: {len(MAPPING)} legacy opcodes")


if __name__ == "__main__":
    main()
